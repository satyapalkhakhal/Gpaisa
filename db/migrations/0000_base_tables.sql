-- Base tables that predate this migrations folder (they were created in the
-- Supabase dashboard). Reconstructed from the live schema so a fresh database can
-- be built entirely from this folder. Idempotent -- safe to re-run.
-- For the production move, data AND schema come from pg_dump (see db/README.md);
-- this file is for fresh/local databases.

-- ── articles ───────────────────────────────────────────────────────────────
-- CMS columns (meta_*, status, updated_at) are added by 0001; ipo_id by 0002.
CREATE TABLE IF NOT EXISTS articles (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    title text NOT NULL,
    slug text NOT NULL,
    category text NOT NULL,
    subcategory text,
    date text NOT NULL,
    published_at timestamptz DEFAULT now(),
    excerpt text NOT NULL,
    content text,
    image_url text NOT NULL,
    author text DEFAULT 'ThinkScope',
    author_avatar text DEFAULT '/placeholder-avatar.jpg',
    read_time text DEFAULT '5 min read',
    tags text[],
    is_featured boolean DEFAULT false,
    is_editors_pick boolean DEFAULT false,
    is_trending boolean DEFAULT false,
    masonry_height text DEFAULT 'medium',
    created_at timestamptz DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_articles_published_at ON articles (published_at DESC);

-- ── subscribers (newsletter) ────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS subscribers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email text NOT NULL,
    status text DEFAULT 'active',
    source text,
    subscribed_at timestamptz DEFAULT now(),
    unsubscribed_at timestamptz,
    created_at timestamptz DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_subscribers_email ON subscribers (email);

-- ── metal_price_history (gold/silver USD daily closes for charts) ───────────
CREATE TABLE IF NOT EXISTS metal_price_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    price_date date NOT NULL,
    gold_usd numeric NOT NULL,
    silver_usd numeric NOT NULL,
    created_at timestamptz DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_metal_price_history_date ON metal_price_history (price_date);
